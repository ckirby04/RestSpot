import { timeZoneAt } from '@restspot/shared'
import type { ImportedListing } from './osm.ts'

const lit = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`)
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`
const QUOTE = '$seed$'

/**
 * SQL that upserts listings by `source_ref`. Re-running an import refreshes OSM
 * fields but never touches listings users have since verified or edited.
 *
 * The whole import is ONE statement (a DO block). Tools like the Supabase SQL
 * editor may not run a long multi-statement script in order in one session, so
 * nothing here depends on state carried between statements.
 */
export function toSql(listings: ImportedListing[], comment: string): string {
  const rows = listings.map((l) => {
    // Most listings have unknown hours; store null and let the column default apply.
    const hours = l.hours.every((d) => d.kind === 'unknown') ? 'null' : json(l.hours)
    return (
      `(${lit(l.sourceRef)}, ${lit(l.source)}, ${lit(l.name)}, ${l.lat}, ${l.lng}, ${lit(timeZoneAt({ lat: l.lat, lng: l.lng }))}, ` +
      `${lit(l.accessType)}, ${lit(l.fee)}, ${lit(l.keyRequired)}, ${hours}, ${lit(l.notes)}, ${l.rooms.length ? json(l.rooms) : 'null'})`
    )
  })
  const values = rows.join(',\n    ')
  if (values.includes(QUOTE)) throw new Error(`Data contains the quote tag ${QUOTE}`)

  return `-- ${comment}
-- Generated by tools/osm-import. Data © OpenStreetMap contributors, ODbL 1.0.
-- Run in the Supabase SQL editor (or psql) as the project owner. Safe to re-run.

do ${QUOTE}
declare
  added int;
  total_osm int;
  total_likely int;
begin
  -- Leftovers from older versions of this script.
  drop schema if exists osm_staging cascade;

  create temporary table osm_import (
    source_ref text primary key, source text, name text, lat double precision, lng double precision, time_zone text,
    access_type text, fee text, key_required text, hours jsonb, notes text, rooms jsonb
  ) on commit drop;

  insert into osm_import values
    ${values}
  on conflict (source_ref) do nothing;

  -- New listings.
  insert into public.locations (name, geog, time_zone, access_type, fee, key_required, hours, notes, source, source_ref, verified)
  select i.name, extensions.st_setsrid(extensions.st_makepoint(i.lng, i.lat), 4326)::extensions.geography,
         i.time_zone, i.access_type, i.fee, i.key_required,
         coalesce(i.hours, '[{"kind":"unknown"},{"kind":"unknown"},{"kind":"unknown"},{"kind":"unknown"},{"kind":"unknown"},{"kind":"unknown"},{"kind":"unknown"}]'::jsonb),
         i.notes, i.source, i.source_ref, false
  from osm_import i
  on conflict (source_ref) do nothing;
  get diagnostics added = row_count;

  -- Refresh imported listings nobody has touched since (only the import created them).
  update public.locations l set
    name = i.name,
    geog = extensions.st_setsrid(extensions.st_makepoint(i.lng, i.lat), 4326)::extensions.geography,
    access_type = i.access_type,
    fee = i.fee,
    key_required = i.key_required,
    hours = coalesce(i.hours, l.hours),
    notes = i.notes,
    updated_at = now()
  from osm_import i
  where l.source_ref = i.source_ref
    and l.source in ('osm', 'poi_inferred')
    and not l.verified
    and not exists (select 1 from public.location_edits e where e.location_id = l.id and e.kind <> 'create');

  -- Rooms for imported listings that don't have any yet.
  insert into public.rooms (location_id, designation, layout, changing_table, ada_accessible, position)
  select l.id, r.value ->> 'designation', r.value ->> 'layout', r.value ->> 'changing_table', r.value ->> 'ada_accessible', r.ordinality - 1
  from osm_import i
  join public.locations l on l.source_ref = i.source_ref
  cross join lateral jsonb_array_elements(coalesce(i.rooms, '[]'::jsonb)) with ordinality r
  where not exists (select 1 from public.rooms x where x.location_id = l.id);

  -- History entry so each listing shows where it came from.
  insert into public.location_edits (location_id, editor_id, kind, snapshot)
  select l.id, null, 'create', public.location_json(l)
  from public.locations l
  join osm_import i on i.source_ref = l.source_ref
  where not exists (select 1 from public.location_edits e where e.location_id = l.id);

  select count(*) filter (where source = 'osm'), count(*) filter (where source = 'poi_inferred')
  into total_osm, total_likely
  from public.locations;
  raise notice 'Added % listings. Now % mapped and % likely restrooms.', added, total_osm, total_likely;
end
${QUOTE};
`
}
